class Recurrence {
  const Recurrence({
    this.kind = RecurrenceKind.none,
    this.weekdays = const {},
    this.interval = 1,
  });

  const Recurrence.daily() : this(kind: RecurrenceKind.daily);
  const Recurrence.weekly() : this(kind: RecurrenceKind.weekly);

  final RecurrenceKind kind;

  /// ISO weekdays (1 = Monday … 7 = Sunday) for [RecurrenceKind.weekdays].
  final Set<int> weekdays;

  /// Step in days for [RecurrenceKind.interval].
  final int interval;

  bool get isRecurring => kind != RecurrenceKind.none;

  /// Whether a day-period quest is scheduled on [day] given its [startDay].
  bool isScheduledOn(String day, String startDay) {
    if (daysBetween(startDay, day) < 0) return false;
    return switch (kind) {
      RecurrenceKind.none => true,
      RecurrenceKind.daily => true,
      RecurrenceKind.weekly => true,
      RecurrenceKind.weekdays =>
        weekdays.isEmpty || weekdays.contains(weekdayOf(day)),
      RecurrenceKind.interval =>
        daysBetween(startDay, day) % (interval < 1 ? 1 : interval) == 0,
    };
  }

  String describe() => switch (kind) {
        RecurrenceKind.none => 'Однократно',
        RecurrenceKind.daily => 'Каждый день',
        RecurrenceKind.weekly => 'Каждую неделю',
        RecurrenceKind.weekdays => weekdays.isEmpty
            ? 'Каждый день'
            : (weekdays.toList()..sort()).map((d) => weekdayShort[d - 1]).join(', '),
        RecurrenceKind.interval => interval == 1
            ? 'Каждый день'
            : 'Каждые $interval ${plural(interval, 'день', 'дня', 'дней')}',
      };

  Json toJson() => {
        'kind': kind.name,
        'weekdays': (weekdays.toList()..sort()),
        'interval': interval,
      };

  factory Recurrence.fromJson(Object? raw) {
    final j = asJson(raw);
    return Recurrence(
      kind: RecurrenceKind.fromName(j['kind'] as String?),
      weekdays: (j['weekdays'] is List)
          ? (j['weekdays'] as List).map((e) => asInt(e)).where((d) => d >= 1 && d <= 7).toSet()
          : const {},
      interval: asInt(j['interval'], 1).clamp(1, 365),
    );
  }
}

class Subtask {
  const Subtask({
    required this.id,
    required this.title,
    this.done = false,
    this.rewarded = false,
  });

  final String id;
  final String title;
  final bool done;

  /// Set once the subtask XP was paid. Never cleared, so toggling a
  /// subtask on and off cannot farm XP.
  final bool rewarded;

  Subtask copyWith({String? title, bool? done, bool? rewarded}) => Subtask(
        id: id,
        title: title ?? this.title,
        done: done ?? this.done,
        rewarded: rewarded ?? this.rewarded,
      );

  Json toJson() => {'id': id, 'title': title, 'done': done, 'rewarded': rewarded};

  factory Subtask.fromJson(Object? raw) {
    final j = asJson(raw);
    return Subtask(
      id: asString(j['id']),
      title: asString(j['title']),
      done: asBool(j['done']),
      rewarded: asBool(j['rewarded']),
    );
  }
}

enum PeriodKind { day, week, once }

class Quest {
  const Quest({
    required this.id,
    required this.title,
    required this.type,
    required this.attribute,
    required this.difficulty,
    required this.xpReward,
    required this.startDay,
    required this.createdAt,
    required this.updatedAt,
    this.description = '',
    this.customXp = false,
    this.recurrence = const Recurrence(),
    this.dueDay,
    this.durationMinutes,
    this.reminderTime,
    this.targetAmount = 1,
    this.unit = MetricUnit.none,
    this.status = QuestStatus.active,
    this.subtasks = const [],
    this.isRecovery = false,
    this.penaltyId,
    this.completedAt,
    this.failedAt,
    this.deleted = false,
  });

  final String id;
  final String title;
  final String description;
  final QuestType type;
  final AttributeType attribute;
  final Difficulty difficulty;

  /// Base XP for one completion (before bonuses).
  final int xpReward;
  final bool customXp;
  final Recurrence recurrence;

  /// Day key the quest becomes active.
  final String startDay;

  /// Deadline (inclusive) for one-off quests.
  final String? dueDay;
  final int? durationMinutes;

  /// "HH:mm" reminder time, local.
  final String? reminderTime;

  /// How much progress closes one period (pages, steps, check-ins…).
  final int targetAmount;
  final MetricUnit unit;
  final QuestStatus status;
  final List<Subtask> subtasks;

  /// Generated by the penalty system to win back a missed obligation.
  final bool isRecovery;
  final String? penaltyId;
  final DateTime? completedAt;
  final DateTime? failedAt;
  final DateTime createdAt;
  final DateTime updatedAt;

  /// Soft delete, so deletion syncs between devices.
  final bool deleted;

  PeriodKind get periodKind => switch (type) {
        QuestType.daily => PeriodKind.day,
        QuestType.weekly => PeriodKind.week,
        _ => PeriodKind.once,
      };

  bool get isRecurring => periodKind != PeriodKind.once;

  /// Boss quests are progressed with one check-in per day.
  bool get usesCheckIns => type == QuestType.boss;

  /// Main quests with subtasks are progressed by subtasks.
  bool get usesSubtasks => type == QuestType.main && subtasks.isNotEmpty;

  /// Whether progress is logged in amounts (e.g. 5000 steps) rather than a
  /// single tap.
  bool get isMeasured => targetAmount > 1 && !usesCheckIns;

  bool get isOpen => !deleted && status == QuestStatus.active;

  double get subtaskProgress => subtasks.isEmpty
      ? 0
      : subtasks.where((s) => s.done).length / subtasks.length;

  Quest copyWith({
    String? title,
    String? description,
    QuestType? type,
    AttributeType? attribute,
    Difficulty? difficulty,
    int? xpReward,
    bool? customXp,
    Recurrence? recurrence,
    String? startDay,
    String? Function()? dueDay,
    int? Function()? durationMinutes,
    String? Function()? reminderTime,
    int? targetAmount,
    MetricUnit? unit,
    QuestStatus? status,
    List<Subtask>? subtasks,
    DateTime? Function()? completedAt,
    DateTime? Function()? failedAt,
    DateTime? updatedAt,
    bool? deleted,
  }) =>
      Quest(
        id: id,
        title: title ?? this.title,
        description: description ?? this.description,
        type: type ?? this.type,
        attribute: attribute ?? this.attribute,
        difficulty: difficulty ?? this.difficulty,
        xpReward: xpReward ?? this.xpReward,
        customXp: customXp ?? this.customXp,
        recurrence: recurrence ?? this.recurrence,
        startDay: startDay ?? this.startDay,
        dueDay: dueDay != null ? dueDay() : this.dueDay,
        durationMinutes:
            durationMinutes != null ? durationMinutes() : this.durationMinutes,
        reminderTime: reminderTime != null ? reminderTime() : this.reminderTime,
        targetAmount: targetAmount ?? this.targetAmount,
        unit: unit ?? this.unit,
        status: status ?? this.status,
        subtasks: subtasks ?? this.subtasks,
        isRecovery: isRecovery,
        penaltyId: penaltyId,
        completedAt: completedAt != null ? completedAt() : this.completedAt,
        failedAt: failedAt != null ? failedAt() : this.failedAt,
        createdAt: createdAt,
        updatedAt: updatedAt ?? this.updatedAt,
        deleted: deleted ?? this.deleted,
      );

  Json toJson() => {
        'id': id,
        'title': title,
        'description': description,
        'type': type.name,
        'attribute': attribute.name,
        'difficulty': difficulty.name,
        'xp_reward': xpReward,
        'custom_xp': customXp,
        'recurrence': recurrence.toJson(),
        'start_day': startDay,
        'due_day': dueDay,
        'duration_minutes': durationMinutes,
        'reminder_time': reminderTime,
        'target_amount': targetAmount,
        'unit': unit.name,
        'status': status.name,
        'subtasks': subtasks.map((s) => s.toJson()).toList(),
        'is_recovery': isRecovery,
        'penalty_id': penaltyId,
        'completed_at': isoOrNull(completedAt),
        'failed_at': isoOrNull(failedAt),
        'created_at': iso(createdAt),
        'updated_at': iso(updatedAt),
        'deleted': deleted,
      };

  factory Quest.fromJson(Json j) {
    final now = DateTime.now();
    return Quest(
      id: asString(j['id']),
      title: asString(j['title']),
      description: asString(j['description']),
      type: QuestType.fromName(j['type'] as String?),
      attribute: AttributeType.fromName(j['attribute'] as String?),
      difficulty: Difficulty.fromName(j['difficulty'] as String?),
      xpReward: asInt(j['xp_reward'], 20),
      customXp: asBool(j['custom_xp']),
      recurrence: Recurrence.fromJson(j['recurrence']),
      startDay: asString(j['start_day'], dayKeyOf(now)),
      dueDay: j['due_day'] as String?,
      durationMinutes: asIntOrNull(j['duration_minutes']),
      reminderTime: j['reminder_time'] as String?,
      targetAmount: asInt(j['target_amount'], 1).clamp(1, 100000000),
      unit: MetricUnit.fromName(j['unit'] as String?),
      status: QuestStatus.fromName(j['status'] as String?),
      subtasks: (j['subtasks'] is List)
          ? (j['subtasks'] as List).map(Subtask.fromJson).toList()
          : const [],
      isRecovery: asBool(j['is_recovery']),
      penaltyId: j['penalty_id'] as String?,
      completedAt: parseDate(j['completed_at']),
      failedAt: parseDate(j['failed_at']),
      createdAt: parseDateOr(j['created_at'], now),
      updatedAt: parseDateOr(j['updated_at'], now),
      deleted: asBool(j['deleted']),
    );
  }
}
